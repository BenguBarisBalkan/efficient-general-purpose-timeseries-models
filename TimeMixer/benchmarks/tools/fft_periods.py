"""Which period would an FFT rule choose for each dataset? (diagnostic, no training)

SparseTSF folds each window by a period taken from its paper (24 for hourly data, 4 for 15- and
10-minute data, 12 for PEMS). TimesNet (Wu et al., 2023) and TimeMixer++ choose periods from the
data instead: the frequency with the largest FFT amplitude gives the period T/f. This tool applies
that rule to each dataset's TRAINING split only:

  1. per channel, remove the mean and take the FFT amplitude over the whole training split;
  2. average the amplitudes over channels;
  3. keep frequencies whose period is between 2 and seq_len / 2 (at least two full periods must
     fit in the 96-step input), and take the strongest;
  4. snap that period to the nearest divisor of seq_len, so the fold needs no padding.

It writes reports/results_fft_periods.md. Whether the chosen period is then worth a training run
is decided from this table against the published period and the period-sensitivity probe.

    venv/Scripts/python.exe benchmarks/tools/fft_periods.py
"""

import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "benchmarks"))

import run as run_module  # noqa: E402
from data_provider.data_factory import data_provider  # noqa: E402

DATA_ROOT = REPO_ROOT.parent / "dataset"
MD_PATH = REPO_ROOT / "reports" / "results_fft_periods.md"
SEQ_LEN = 96

# (name, data, root, file, published SparseTSF period)
DATASETS = [
    ("ETTh1", "ETTh1", "ETT-small", "ETTh1.csv", 24),
    ("ETTh2", "ETTh2", "ETT-small", "ETTh2.csv", 24),
    ("ETTm1", "ETTm1", "ETT-small", "ETTm1.csv", 4),
    ("ETTm2", "ETTm2", "ETT-small", "ETTm2.csv", 4),
    ("Weather", "custom", "weather", "weather.csv", 4),
    ("PEMS03", "PEMS", "PEMS", "PEMS03.npz", 12),
    ("PEMS04", "PEMS", "PEMS", "PEMS04.npz", 12),
    ("PEMS07", "PEMS", "PEMS", "PEMS07.npz", 12),
    ("PEMS08", "PEMS", "PEMS", "PEMS08.npz", 12),
]


def train_matrix(data: str, root: str, path: str) -> np.ndarray:
    pred = "12" if data == "PEMS" else "96"
    args = run_module.parser.parse_args([
        "--task_name", "long_term_forecast", "--is_training", "1", "--model_id", "fft",
        "--model", "SparseTSF", "--data", data, "--root_path", str(DATA_ROOT / root),
        "--data_path", path, "--features", "M", "--seq_len", str(SEQ_LEN), "--label_len", "0",
        "--pred_len", pred, "--num_workers", "0"])
    ds, _ = data_provider(args, "train")
    return np.asarray(ds.data_x, dtype=np.float64)          # (time, channels), training split


def fft_period(x: np.ndarray):
    x = x - x.mean(axis=0, keepdims=True)
    n = x.shape[0]
    amp = np.abs(np.fft.rfft(x, axis=0)).mean(axis=1)       # mean amplitude over channels
    freqs = np.arange(len(amp))
    with np.errstate(divide="ignore"):
        periods = np.where(freqs > 0, n / np.maximum(freqs, 1), np.inf)
    ok = (periods >= 2) & (periods <= SEQ_LEN // 2)
    best = int(np.argmax(np.where(ok, amp, -1.0)))
    raw = periods[best]
    divisors = [d for d in range(2, SEQ_LEN // 2 + 1) if SEQ_LEN % d == 0]
    snapped = min(divisors, key=lambda d: (abs(d - raw), d))
    # strength: the chosen peak against the median amplitude of the allowed band
    strength = amp[best] / np.median(amp[ok])
    return raw, snapped, strength


def main():
    rows = []
    for name, data, root, path, published in DATASETS:
        x = train_matrix(data, root, path)
        raw, snapped, strength = fft_period(x)
        rows.append((name, published, raw, snapped, strength, x.shape))
        print("{:<8} published {:>3}  fft {:7.2f} -> {:>3}  peak/median {:6.1f}  train {}".format(
            name, published, raw, snapped, strength, x.shape), flush=True)
    lines = [
        "# Periods chosen by an FFT rule", "",
        "Generated by `benchmarks/tools/fft_periods.py` from each dataset's training split only.",
        "The rule (as in TimesNet and TimeMixer++): the frequency with the largest mean FFT amplitude",
        "among periods from 2 to 48 steps (at least two full periods in the 96-step input), snapped",
        "to the nearest divisor of 96. Peak/median compares the chosen peak with the median",
        "amplitude of that band.", "",
        "| Dataset | Published period | FFT period | Snapped | Peak / median | Training steps × channels |",
        "|---|---:|---:|---:|---:|---|"]
    for name, published, raw, snapped, strength, shape in rows:
        lines.append("| {} | {} | {:.2f} | {}{} | {:.1f} | {} × {} |".format(
            name, published, raw, snapped, "" if snapped == published else " (differs)",
            strength, shape[0], shape[1]))
    MD_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("[OK] wrote " + str(MD_PATH.relative_to(REPO_ROOT)))


if __name__ == "__main__":
    main()
